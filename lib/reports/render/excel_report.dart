/// A [TenantReportDocument], written as a workbook.
///
/// **Cells carry numbers, not sentences.** The whole reason somebody picks the
/// spreadsheet over the PDF is to sort it, total it and chart it themselves,
/// and a column of `"KES 1234.50"` strings can do none of those. So money goes
/// in as a double with a currency number format, a count goes in as an integer,
/// a share goes in as a fraction with a percent format so Excel's own percent
/// semantics apply, and a business date goes in as a date. The ISO code lives
/// in the number format and in the column heading; it is never concatenated
/// into the value.
///
/// **The same document, the same sections, the same figures as the PDF.** Both
/// renderers walk one [TenantReportDocument] and neither knows which report it
/// is drawing, so the two cannot come to different conclusions about what the
/// business took last month.
library;

import 'dart:typed_data';

import 'package:excel/excel.dart';

import '../report_document.dart';
import '../report_file.dart';
import '../report_table.dart';
import 'workbook_palette.dart';

/// Renders a report as an .xlsx workbook.
final class TenantExcelReportRenderer {
  const TenantExcelReportRenderer({required this.palette});

  factory TenantExcelReportRenderer.standard() => TenantExcelReportRenderer(
    palette: TenantReportWorkbookPalette.standard,
  );

  final TenantReportWorkbookPalette palette;

  /// The sheet `Excel.createExcel` starts with, which is deleted once this
  /// workbook has one of its own - a workbook cannot be left with no sheets.
  static const String _scaffoldSheet = 'Sheet1';

  static const String coverSheet = 'Report';
  static const String summarySheet = 'Summary';

  Future<TenantReportFile> render(TenantReportDocument document) async {
    final book = Excel.createExcel();

    _writeCover(book, document);
    _writeSummary(book, document);
    for (final section in document.sections) {
      if (section.table case final table?) {
        _writeTable(book, document, section, table);
      }
    }

    book.setDefaultSheet(coverSheet);
    if (book.sheets.containsKey(_scaffoldSheet)) {
      book.delete(_scaffoldSheet);
    }

    final bytes = book.encode();
    if (bytes == null) {
      throw StateError('the workbook produced no bytes');
    }

    return TenantReportFile(
      filename: document.filename(TenantReportFormat.excel),
      bytes: Uint8List.fromList(bytes),
      mimeType: TenantReportFormat.excel.mimeType,
      subject: document.shareSubject,
      text: document.shareText,
    );
  }

  // ---------------------------------------------------------------------------
  // The cover
  // ---------------------------------------------------------------------------

  void _writeCover(Excel book, TenantReportDocument document) {
    final sheet = book[coverSheet];
    final identity = document.identity;
    var row = 0;

    sheet.setColumnWidth(0, _labelColumnWidth);
    sheet.setColumnWidth(1, _valueColumnWidth);

    // The branding band. Merged across both columns and set in the accent,
    // because this is the only mark a workbook can carry - `excel` cannot
    // embed an image, so the name has to do the work the logo does on paper.
    _put(sheet, 0, row, TextCellValue(identity.businessName), _brandStyle);
    sheet.merge(_at(0, row), _at(1, row));
    sheet.setRowHeight(row, _brandRowHeight);
    row++;

    if (identity.slogan case final slogan?) {
      _put(sheet, 0, row, TextCellValue(slogan), _mutedStyle);
      sheet.merge(_at(0, row), _at(1, row));
      row++;
    }
    row++;

    _put(sheet, 0, row, TextCellValue(document.title), _titleStyle);
    sheet.merge(_at(0, row), _at(1, row));
    row++;
    _put(sheet, 0, row, TextCellValue(document.period.spelled), _bodyStyle);
    sheet.merge(_at(0, row), _at(1, row));
    row++;
    _put(sheet, 0, row, TextCellValue(document.subtitle), _mutedStyle);
    sheet.merge(_at(0, row), _at(1, row));
    row += 2;

    row = _heading(sheet, row, 'Scope and provenance');
    row = _pair(sheet, row, 'Covers', document.period.spelled);
    row = _pair(
      sheet,
      row,
      'Records read',
      document.scope.documentsRead.toString(),
    );
    row = _pair(
      sheet,
      row,
      'Complete',
      document.scope.isComplete ? 'Yes' : 'No - see the notes below',
    );
    row = _pair(
      sheet,
      row,
      'Currency',
      identity.currency.code ?? 'Not published',
    );
    row = _pair(sheet, row, 'Generated', _stamp(identity.generatedAt));
    row = _pair(
      sheet,
      row,
      'Generated by',
      identity.generatedBy,
    );

    final caveats = document.caveats;
    if (caveats.isEmpty) return;

    row++;
    row = _heading(sheet, row, 'What this report could not do');
    for (final caveat in caveats) {
      _put(sheet, 0, row, TextCellValue(caveat), _wrappedStyle);
      sheet.merge(_at(0, row), _at(1, row));
      sheet.setRowHeight(row, _caveatRowHeight);
      row++;
    }
  }

  // ---------------------------------------------------------------------------
  // The summary
  // ---------------------------------------------------------------------------

  /// Every figure the report draws, as rows that can be totalled.
  ///
  /// **This is the sheet that makes the workbook worth having.** The PDF's
  /// charts are pictures of these numbers; here they are the numbers, with the
  /// preceding period beside each one and the change already worked out. It is
  /// also why the workbook needs no chart images to be useful.
  void _writeSummary(Excel book, TenantReportDocument document) {
    final sheet = book[summarySheet];
    final code = document.identity.currency.code;
    var row = 0;

    sheet.setColumnWidth(0, _sectionColumnWidth);
    sheet.setColumnWidth(1, _labelColumnWidth);
    for (var column = 2; column <= 4; column++) {
      sheet.setColumnWidth(column, _figureColumnWidth);
    }

    for (final (index, heading) in <String>[
      'Section',
      'Measure',
      'This period',
      'Period before',
      'Change',
    ].indexed) {
      _put(sheet, index, row, TextCellValue(heading), _headerStyle);
    }
    row++;

    for (final figure in document.headline) {
      _put(sheet, 0, row, TextCellValue('Headline'), _bodyStyle);
      _put(sheet, 1, row, TextCellValue(figure.label), _bodyStyle);
      // **The raw number where the analysis kept one.** These are the figures
      // somebody is most likely to reference, so writing takings into a
      // spreadsheet as the string `KES 4863.50` would take away the one thing
      // they opened it to do. The pre-formatted text is the fallback for a
      // figure with no single number behind it.
      _putFigure(sheet, 2, row, figure.amount, figure.value, figure, code);
      _putFigure(
        sheet,
        3,
        row,
        figure.amountComparison,
        figure.comparison ?? '',
        figure,
        code,
      );
      _put(sheet, 4, row, TextCellValue(figure.note ?? ''), _mutedStyle);
      row++;
    }

    for (final section in document.sections) {
      if (section.visual case final visual?) {
        for (final datum in visual.data) {
          _put(sheet, 0, row, TextCellValue(section.heading), _bodyStyle);
          _put(sheet, 1, row, TextCellValue(datum.label), _bodyStyle);
          _put(
            sheet,
            2,
            row,
            DoubleCellValue(datum.value),
            _numberStyle(_moneyFormat(code)),
          );
          if (datum.comparison case final was?) {
            _put(
              sheet,
              3,
              row,
              DoubleCellValue(was),
              _numberStyle(_moneyFormat(code)),
            );
          }
          if (datum.change case final moved?) {
            _put(
              sheet,
              4,
              row,
              DoubleCellValue(moved),
              _numberStyle(NumFormat.custom(formatCode: _percentFormat)),
            );
          }
          row++;
        }
      }
    }
  }

  // ---------------------------------------------------------------------------
  // One sheet per listed section
  // ---------------------------------------------------------------------------

  void _writeTable(
    Excel book,
    TenantReportDocument document,
    TenantReportSection section,
    TenantReportTable table,
  ) {
    final name = _uniqueSheetName(book, section.sheetName);
    final sheet = book[name];
    final code = document.identity.currency.code;
    var row = 0;

    _put(sheet, 0, row, TextCellValue(section.summary), _wrappedStyle);
    sheet.merge(_at(0, row), _at(table.columns.length - 1, row));
    sheet.setRowHeight(row, _caveatRowHeight);
    row += 2;

    for (final (index, column) in table.columns.indexed) {
      // The code goes in the heading as well as the number format, so a column
      // pasted somewhere else still says what it is denominated in.
      final heading = switch (column.kind) {
        TenantReportColumnKind.money when code != null =>
          '${column.heading} ($code)',
        _ => column.heading,
      };
      _put(sheet, index, row, TextCellValue(heading), _headerStyle);
      sheet.setColumnWidth(
        index,
        column.isNumeric ? _figureColumnWidth : _labelColumnWidth,
      );
    }
    row++;

    for (final line in table.rows) {
      for (final (index, cell) in line.indexed) {
        _writeCell(sheet, index, row, cell, code);
      }
      row++;
    }

    for (final note in section.notes) {
      row++;
      _put(sheet, 0, row, TextCellValue(note), _wrappedStyle);
      sheet.merge(_at(0, row), _at(table.columns.length - 1, row));
      sheet.setRowHeight(row, _caveatRowHeight);
    }
  }

  void _writeCell(
    Sheet sheet,
    int column,
    int row,
    TenantReportCell cell,
    String? code,
  ) {
    switch (cell) {
      case TenantReportTextCell(:final value):
        _put(sheet, column, row, TextCellValue(value), _bodyStyle);
      case TenantReportMoneyCell(:final major):
        _put(
          sheet,
          column,
          row,
          DoubleCellValue(major),
          _numberStyle(_moneyFormat(code)),
        );
      case TenantReportCountCell(:final value):
        _put(
          sheet,
          column,
          row,
          IntCellValue(value),
          _numberStyle(NumFormat.custom(formatCode: _countFormat)),
        );
      case TenantReportPercentCell(:final fraction):
        _put(
          sheet,
          column,
          row,
          DoubleCellValue(fraction),
          _numberStyle(NumFormat.custom(formatCode: _percentFormat)),
        );
      case TenantReportDateCell(:final businessDate):
        _put(
          sheet,
          column,
          row,
          TextCellValue(businessDate),
          _bodyStyle,
        );
      // **Words, in a text cell, on purpose.** A blank here would be summed as
      // nought by whoever opens the file and a nought would invent a
      // measurement nobody took. Neither is a thing this report is allowed to
      // say, so the cell says what it means and cannot be coerced to a number.
      case TenantReportAbsentCell():
        _put(sheet, column, row, TextCellValue(cell.text), _absentStyle);
    }
  }

  // ---------------------------------------------------------------------------
  // Sheet plumbing
  // ---------------------------------------------------------------------------

  void _put(
    Sheet sheet,
    int column,
    int row,
    CellValue value,
    CellStyle style,
  ) => sheet.updateCell(_at(column, row), value, cellStyle: style);

  /// A headline figure as a number where one was kept, as its text otherwise.
  void _putFigure(
    Sheet sheet,
    int column,
    int row,
    num? amount,
    String written,
    TenantReportFigure figure,
    String? code,
  ) {
    if (amount == null) {
      _put(sheet, column, row, TextCellValue(written), _figureTextStyle);
      return;
    }
    final format = switch (figure.amountKind) {
      TenantReportColumnKind.money => _moneyFormat(code),
      TenantReportColumnKind.percent => NumFormat.custom(
        formatCode: _percentFormat,
      ),
      _ => NumFormat.custom(formatCode: _countFormat),
    };
    _put(
      sheet,
      column,
      row,
      figure.amountKind == TenantReportColumnKind.count
          ? IntCellValue(amount.round())
          : DoubleCellValue(amount.toDouble()),
      _numberStyle(format),
    );
  }

  static CellIndex _at(int column, int row) =>
      CellIndex.indexByColumnRow(columnIndex: column, rowIndex: row);

  int _heading(Sheet sheet, int row, String text) {
    _put(sheet, 0, row, TextCellValue(text), _headerStyle);
    _put(sheet, 1, row, TextCellValue(''), _headerStyle);
    return row + 1;
  }

  int _pair(Sheet sheet, int row, String label, String value) {
    _put(sheet, 0, row, TextCellValue(label), _labelStyle);
    _put(sheet, 1, row, TextCellValue(value), _bodyStyle);
    return row + 1;
  }

  /// Two sections can share a heading, and Excel refuses a duplicate tab name.
  String _uniqueSheetName(Excel book, String preferred) {
    if (!book.sheets.containsKey(preferred)) return preferred;
    for (var suffix = 2; suffix < 50; suffix++) {
      final candidate = '$preferred $suffix';
      if (candidate.length <= _sheetNameLimit &&
          !book.sheets.containsKey(candidate)) {
        return candidate;
      }
    }
    return preferred.substring(0, _sheetNameLimit - 4);
  }

  // ---------------------------------------------------------------------------
  // Styles and formats
  // ---------------------------------------------------------------------------

  /// Money, with the ISO code in the format rather than in the value.
  ///
  /// A business that has published no currency gets a bare number, which is
  /// `TenantReportingCurrency`'s rule reaching the spreadsheet: there is no
  /// defensible default and a wrong code is worse than none.
  NumFormat _moneyFormat(String? code) => NumFormat.custom(
    formatCode: code == null ? _plainMoneyFormat : '"$code" #,##0.00',
  );

  CellStyle get _brandStyle => CellStyle(
    bold: true,
    fontSize: _brandFontSize,
    fontColorHex: palette.accent,
    verticalAlign: VerticalAlign.Center,
  );

  CellStyle get _titleStyle =>
      CellStyle(bold: true, fontSize: _titleFontSize, fontColorHex: palette.ink);

  CellStyle get _headerStyle => CellStyle(
    bold: true,
    fontColorHex: palette.ink,
    backgroundColorHex: palette.wash,
    bottomBorder: Border(borderStyle: BorderStyle.Thin, borderColorHex: palette.rule),
  );

  CellStyle get _labelStyle =>
      CellStyle(bold: true, fontColorHex: palette.mutedInk);

  CellStyle get _bodyStyle => CellStyle(fontColorHex: palette.ink);

  CellStyle get _mutedStyle => CellStyle(fontColorHex: palette.mutedInk);

  CellStyle get _wrappedStyle => CellStyle(
    fontColorHex: palette.mutedInk,
    textWrapping: TextWrapping.WrapText,
    verticalAlign: VerticalAlign.Top,
  );

  /// An unknown value, set apart so it reads as absent at a glance.
  CellStyle get _absentStyle => CellStyle(
    fontColorHex: palette.mutedInk,
    italic: true,
    horizontalAlign: HorizontalAlign.Right,
  );

  /// A pre-formatted figure that is text rather than a number.
  CellStyle get _figureTextStyle => CellStyle(
    fontColorHex: palette.ink,
    horizontalAlign: HorizontalAlign.Right,
  );

  CellStyle _numberStyle(NumFormat format) => CellStyle(
    fontColorHex: palette.ink,
    horizontalAlign: HorizontalAlign.Right,
    numberFormat: format,
  );

  static const String _plainMoneyFormat = '#,##0.00';
  static const String _countFormat = '#,##0';
  static const String _percentFormat = '0.0%';

  static const int _brandFontSize = 18;
  static const int _titleFontSize = 13;
  static const double _brandRowHeight = 28;
  static const double _caveatRowHeight = 30;
  static const double _labelColumnWidth = 26;
  static const double _valueColumnWidth = 52;
  static const double _sectionColumnWidth = 24;
  static const double _figureColumnWidth = 16;
  static const int _sheetNameLimit = 31;

  static String _stamp(DateTime at) {
    final local = at.toUtc().add(const Duration(hours: 3));
    final month = local.month.toString().padLeft(2, '0');
    final day = local.day.toString().padLeft(2, '0');
    final hour = local.hour.toString().padLeft(2, '0');
    final minute = local.minute.toString().padLeft(2, '0');
    return '${local.year}-$month-$day $hour:$minute';
  }
}
